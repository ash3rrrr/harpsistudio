//! Export the Vocal Riddim factory demo through the same paths the GUI uses.
//!
//! Run from `harpsistudio/`:
//!   cargo run -p hs-core --example render_vocal_riddim
//!
//! Outputs:
//! - `demo-artifacts/projects/Vocal Riddim.harp`
//! - `demo-artifacts/renders/vocal-riddim.wav`
//! - `demo-artifacts/renders/vocal-riddim-vocal-stem.wav`
//! - `demo-artifacts/reports/vocal-riddim.md`

use hs_core::presets;
use hs_core::project;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

fn main() {
    let app_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    let artifacts = app_dir.join("demo-artifacts");
    let projects = artifacts.join("projects");
    let renders = artifacts.join("renders");
    let reports = artifacts.join("reports");
    fs::create_dir_all(&projects).expect("create projects directory");
    fs::create_dir_all(&renders).expect("create renders directory");
    fs::create_dir_all(&reports).expect("create reports directory");

    let song = presets::demo_song(10);
    assert_eq!(song.name, "Vocal Riddim");
    assert_eq!(song.length_beats(), 64.0);
    assert!(
        song.tracks
            .iter()
            .any(|t| t.name == "Vocal Hook" && t.take.is_some()),
        "Vocal Riddim is missing its vocal hook"
    );
    assert!(
        song.tracks
            .iter()
            .any(|t| t.name == "Vocal Growl" && t.take.is_some()),
        "Vocal Riddim is missing its vocal bass"
    );

    let project_path = projects.join(format!("{}.harp", project::sanitize(&song.name)));
    project::save_song_to(&song, &project_path).expect("save vocal riddim project");
    let loaded = project::load_song(&project_path).expect("reload saved vocal riddim");
    assert_eq!(loaded.length_beats(), 64.0);
    assert_eq!(
        loaded.tracks.iter().filter(|t| t.take.is_some()).count(),
        song.tracks.iter().filter(|t| t.take.is_some()).count()
    );

    let mix_path = renders.join("vocal-riddim.wav");
    project::export_wav_to(&loaded, &mix_path).expect("render vocal riddim mixdown");

    let mut vocal_stem = loaded.clone();
    for track in &mut vocal_stem.tracks {
        track.mute = !matches!(
            track.name.as_str(),
            "Vocal Hook" | "Vocal Growl" | "Vocal Harmony"
        );
    }
    let stem_path = renders.join("vocal-riddim-vocal-stem.wav");
    project::export_wav_to(&vocal_stem, &stem_path).expect("render vocal stem");

    let mut report = String::new();
    report.push_str("# Vocal Riddim\n\n");
    report.push_str("Generated by `cargo run -p hs-core --example render_vocal_riddim`.\n\n");
    writeln!(
        report,
        "- 16 bars / 64 beats at {:.0} BPM, A minor.",
        song.bpm
    )
    .unwrap();
    report.push_str(
        "- Load path: START → FACTORY DEMOS → Vocal Riddim (`presets::demo_song(10)`).\n",
    );
    report.push_str(
        "- Mixdown: `project::export_wav_to`, the same renderer behind the Mixdown button.\n\n",
    );
    report.push_str("| Track | Device | Arrangement notes | Source |\n");
    report.push_str("| --- | --- | ---: | --- |\n");
    for track in &song.tracks {
        let notes: usize = track
            .clips
            .iter()
            .filter(|c| c.scene < 0)
            .map(|c| c.notes.len())
            .sum();
        writeln!(
            report,
            "| {} | {} | {} | {} |",
            track.name,
            track.instrument.kind.name(),
            notes,
            if track.take.is_some() {
                "embedded vocal take"
            } else {
                "synth / samples"
            }
        )
        .unwrap();
    }
    report.push_str("\n## Arrangement\n\n");
    report.push_str("- Bars 1–4: chopped vocal hook, dark pad and a sweep into the first drop.\n");
    report.push_str("- Bars 5–8: half-time drop with vocal growl, sub and synth growl bass.\n");
    report.push_str(
        "- Bars 9–12: drums and bass out; vocal hook and piano answer carry the break.\n",
    );
    report.push_str("- Bars 13–16: second drop adds the vocal harmony and a final sweep.\n\n");
    report.push_str("The `.harp` project embeds the take, so it opens without the source WAV.\n");
    fs::write(reports.join("vocal-riddim.md"), report).expect("write vocal riddim report");

    println!("project: {}", project_path.display());
    println!("mix:     {}", mix_path.display());
    println!("stem:    {}", stem_path.display());
}
